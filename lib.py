#STUDENT CLASS
class Student:
    def __init__(self, full_name, campus, password, short_bio, repo_link, rank):
        self.full_name = full_name
        self.campus    = campus
        self.password  = password
        self.short_bio = short_bio
        self.repo_link = repo_link
        self.rank      = rank
